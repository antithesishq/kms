#!/bin/sh
# Renders the public_decrypt test template into a ConfigMap manifest. The kms-core-client pod
# mounts that ConfigMap at /opt/antithesis/test/v1/public_decrypt/, so the scripts reach the
# cluster without a rebuild of the core-client image.
#
# Every *.py file in v1/public_decrypt/ goes into the ConfigMap. A new file also needs its own
# subPath mount in ../config/manifests/40-kms-core-init.yaml.
#
# Run this after every edit under v1/public_decrypt/, then apply the manifest and restart the
# client pod (subPath mounts do not pick up ConfigMap changes):
#   ./render-configmap.sh
#   kubectl apply -f ../config/manifests/41-kms-workload-tests.yaml
#   kubectl delete pod kms-core-client-0 -n kms-threshold-staging
set -eu

here=$(cd "$(dirname "$0")" && pwd)
src="$here/v1/public_decrypt"
out="$here/../config/manifests/41-kms-workload-tests.yaml"

{
  echo "# GENERATED by antithesis/test/render-configmap.sh from antithesis/test/v1/public_decrypt/."
  echo "# Edit the scripts there and re-run the generator. Do not edit this file."
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: kms-workload-tests"
  echo "  namespace: kms-threshold-staging"
  echo "data:"
  for path in "$src"/*.py; do
    echo "  ${path##*/}: |"
    sed 's/^\(.\)/    \1/' "$path"
  done
} >"$out"

echo "wrote $out"
