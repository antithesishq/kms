#!/bin/sh
# Renders the main test template into a ConfigMap manifest. The kms-core-client pod mounts
# that ConfigMap file by file at /opt/antithesis/test/v1/main/, so the commands reach the
# cluster without a rebuild of the core-client image.
#
# Every *.py file in v1/main/ goes into the ConfigMap. The script also rewrites the pod's
# subPath mounts for them in ../config/manifests/40-kms-core-init.yaml, between the
# "BEGIN generated" and "END generated" comment lines.
#
# Run this after every edit under v1/main/, then apply the manifests and restart the client
# pod (subPath mounts do not pick up ConfigMap changes):
#   ./render-configmap.sh
#   kubectl apply -f ../config/manifests/41-kms-workload-tests.yaml
#   kubectl delete pod kms-core-client-0 -n kms-threshold-staging
set -eu

here=$(cd "$(dirname "$0")" && pwd)
src="$here/v1/main"
out="$here/../config/manifests/41-kms-workload-tests.yaml"
pod="$here/../config/manifests/40-kms-core-init.yaml"
mount_dir=/opt/antithesis/test/v1/main

{
  echo "# GENERATED by antithesis/test/render-configmap.sh from antithesis/test/v1/main/."
  echo "# Edit the scripts there and re-run the generator. Do not edit this file."
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: kms-workload-tests"
  echo "  namespace: kms-threshold-staging"
  echo "data:"
  for path in "$src"/*.py; do
    echo "  ${path##*/}: |"
    sed 's/^\(.\)/    \1/' "$path"
  done
} >"$out"

mounts=$(mktemp)
trap 'rm -f "$mounts" "$pod.tmp"' EXIT
for path in "$src"/*.py; do
  printf '        - mountPath: %s/%s\n          subPath: %s\n          name: workload-tests\n' \
    "$mount_dir" "${path##*/}" "${path##*/}"
done >"$mounts"
grep -q '# BEGIN generated by test/render-configmap.sh' "$pod" || {
  echo "no BEGIN generated marker in $pod" >&2
  exit 1
}
awk -v mounts="$mounts" '
  /# BEGIN generated by test\/render-configmap.sh/ { print; while ((getline l < mounts) > 0) print l; skip = 1; next }
  /# END generated by test\/render-configmap.sh/ { skip = 0 }
  !skip { print }
' "$pod" >"$pod.tmp"
mv "$pod.tmp" "$pod"

echo "wrote $out and the workload-tests mounts in $pod"
