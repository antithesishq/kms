"""Shared helpers for the public_decrypt test template. Imported by the test commands; the
helper_ prefix makes Antithesis skip this file when it picks commands to run.

Assertions and randomness come from the Antithesis Python SDK, which images/client.Dockerfile
installs in the core-client image. In Antithesis the SDK reports through libvoidstar. Without
libvoidstar it writes JSON lines to $ANTITHESIS_SDK_LOCAL_OUTPUT, which this module points at
$ANTITHESIS_OUTPUT_DIR/sdk.jsonl when that is set, and at /tmp/antithesis-sdk.jsonl otherwise
(hand-driving with kubectl exec).

Import this module before anything from antithesis: the SDK picks its output when it loads.
"""

import atexit
import hashlib
import http.client
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from dataclasses import replace

if os.environ.get("ANTITHESIS_OUTPUT_DIR"):
    _local_output = os.path.join(os.environ["ANTITHESIS_OUTPUT_DIR"], "sdk.jsonl")
else:
    _local_output = "/tmp/antithesis-sdk.jsonl"
os.environ.setdefault("ANTITHESIS_SDK_LOCAL_OUTPUT", _local_output)

# A command that Antithesis kills mid-run still leaves its output so far in the logs.
sys.stdout.reconfigure(line_buffering=True)

from antithesis import catalog  # noqa: E402
from antithesis.random import get_random, random_choice  # noqa: E402

TEMPLATE_DIR = os.path.dirname(os.path.abspath(__file__))
CLIENT_DIR = "/app/kms-core-client"  # config.toml is written here when the pod starts
S3_PUBLIC = "http://minio:9000/kms-public"

# State that the test commands share. All of them run in the kms-core-client container, so a
# directory in its /tmp is enough. The state is lost when the container restarts.
#   preproc/<key_id>  the preprocessing ID of the key (written by first_generate_key.py)
#   epochs            one line per reshare: <epoch_id> <key_id> confirmed|unconfirmed
STATE_DIR = "/tmp/kms-workload-state"
EPOCHS_FILE = os.path.join(STATE_DIR, "epochs")

# The context and epoch that kms-init creates (DEFAULT_MPC_CONTEXT and DEFAULT_EPOCH_ID in
# core/service/src/consts.rs). A request with no epoch ID goes to this epoch.
DEFAULT_CONTEXT_ID = "0700000000000000000000000000000000000000000000000000000000000001"
DEFAULT_EPOCH_ID = "0800000000000000000000000000000000000000000000000000000000000001"


def declare_catalog():
    """Declare every assertion in the template, so that a never-reached Always or Reachable
    still shows up as failing.

    The platform catalogs only Python files that are in the image, and these come from a
    ConfigMap. So each command scans the template at startup and declares what it finds,
    the way an instrumented process declares its catalog. The scan sees only SDK assertion
    calls with a literal message, so the commands spell their messages out at each call.
    """
    catalog.register(
        replace(a, location=replace(a.location, file=os.path.join(TEMPLATE_DIR, a.location.file)))
        for a in catalog.scan_tree(TEMPLATE_DIR)
    )


def pick(*choices):
    """One of CHOICES, chosen by Antithesis. Repeat a choice to weight it."""
    return random_choice(list(choices))


def random_hex(n):
    """N random bytes from Antithesis, as hex."""
    out = b""
    while len(out) < n:
        out += get_random().to_bytes(8, "little")
    return out[:n].hex()


def pick_value(data_type):
    """A little-endian hex value for DATA_TYPE (as kms-core-client --to-encrypt reads it), drawn
    from the type's value menu: zero, one, the maximum, only the top bit set, or uniformly random
    bits. Random values keep requests distinguishable from each other."""
    if data_type == "ebool":
        return pick("00", "01")
    n = int(data_type[len("euint"):]) // 8
    kind = pick("zero", "one", "max", "top", "random", "random")
    if kind == "zero":
        return "00" * n
    if kind == "one":
        return "01" + "00" * (n - 1)
    if kind == "max":
        return "ff" * n
    if kind == "top":
        return "00" * (n - 1) + "80"
    return random_hex(n)


def fetch(url):
    """The body at URL, or None when it cannot be read."""
    try:
        with urllib.request.urlopen(url, timeout=60) as response:
            return response.read()
    except (OSError, http.client.HTTPException):
        return None


def find_key_id():
    """The ID of an FHE key that party 1 has published, at random if there are several. Keys
    are looked up in MinIO rather than a local file, so a key generated by hand is found too.
    None when there is none (or MinIO is unreachable)."""
    listing = fetch(f"{S3_PUBLIC}?list-type=2&prefix=PUB-p1/PublicKey/")
    if listing is None:
        return None
    ids = re.findall(r"<Key>PUB-p1/PublicKey/([^<]*)</Key>", listing.decode(errors="replace"))
    return random_choice(ids) if ids else None


def request_id_from(output):
    """The request ID from kms-core-client's success line, <msg> - "request_id": "<id>"."""
    ids = re.findall(r'"request_id": "([0-9a-fA-F]*)"', output)
    return ids[-1] if ids and ids[-1] else None


def enter_scratch_dir():
    """cd into a fresh directory holding a copy of config.toml. The CLI downloads key material
    into ./keys on every run, so concurrent runs sharing a directory would overwrite each
    other's files."""
    scratch = tempfile.mkdtemp(prefix="kms-workload.")
    atexit.register(shutil.rmtree, scratch, ignore_errors=True)
    shutil.copy(os.path.join(CLIENT_DIR, "config.toml"), scratch)
    os.chdir(scratch)


def run_cli(args, timeout=None):
    """Run kms-core-client with ARGS. Returns its exit code and its output (stdout and stderr).
    A run that outlasts TIMEOUT seconds is stopped and exits 124, as under timeout(1)."""
    print("kms-core-client " + " ".join(args))
    with tempfile.TemporaryFile() as out:
        proc = subprocess.Popen(["kms-core-client", *args], stdout=out, stderr=subprocess.STDOUT)
        try:
            rc = proc.wait(timeout)
        except subprocess.TimeoutExpired:
            proc.terminate()
            try:
                proc.wait(10)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
            rc = 124
        out.seek(0)
        return rc, out.read().decode(errors="replace")


def first_line_with(output, patterns):
    """The first line of OUTPUT that contains one of PATTERNS, or None."""
    for line in output.splitlines():
        if any(p in line for p in patterns):
            return line
    return None


def tail(output, n):
    return "\n".join(output.splitlines()[-n:])


def clip(text):
    """TEXT as one line of printable ASCII, capped in length: error output is just context for
    triage."""
    text = text.translate(str.maketrans("\n\r\t", "   "))
    return "".join(c for c in text if " " <= c <= "~")[:400]


def record_preproc(key_id, preproc_id):
    """Remember the preprocessing ID of a key. A reshare request must carry the ID that the key
    was generated from, and no public object records it."""
    os.makedirs(os.path.join(STATE_DIR, "preproc"), exist_ok=True)
    with open(os.path.join(STATE_DIR, "preproc", key_id), "w") as f:
        f.write(preproc_id + "\n")


def find_reshare_key():
    """(key_id, preproc_id) for a key with a recorded preprocessing ID, at random if there are
    several. None when there is none."""
    try:
        keys = sorted(os.listdir(os.path.join(STATE_DIR, "preproc")))
    except FileNotFoundError:
        return None
    if not keys:
        return None
    key_id = random_choice(keys)
    with open(os.path.join(STATE_DIR, "preproc", key_id)) as f:
        return key_id, f.read().strip()


def record_epoch(epoch_id, key_id, status):
    """Record a reshare, STATUS confirmed or unconfirmed. One short line, appended with a single
    write, so lines from concurrent commands do not mix."""
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(EPOCHS_FILE, "a") as f:
        f.write(f"{epoch_id} {key_id} {status}\n")


def epochs_of(key_id, status):
    """The recorded epochs with STATUS that KEY_ID was reshared into."""
    try:
        with open(EPOCHS_FILE) as f:
            return [fields[0] for fields in map(str.split, f) if fields[1:] == [key_id, status]]
    except FileNotFoundError:
        return []


def pick_epoch(key_id):
    """(epoch_id, status) for a public decryption under KEY_ID. STATUS is default (the kms-init
    epoch), confirmed (every core reported the reshare as done) or unconfirmed (the reshare CLI
    failed, so some cores can hold the epoch and others not). Falls back to the default epoch
    when no reshared epoch of the chosen kind exists."""
    status = pick("default", "default", "confirmed", "confirmed", "unconfirmed")
    if status != "default":
        epochs = epochs_of(key_id, status)
        if epochs:
            return random_choice(epochs), status
    return DEFAULT_EPOCH_ID, "default"


def new_epoch_id():
    """A random epoch ID. It starts with 0x08 like DEFAULT_EPOCH_ID, which is the prefix that
    fhevm expects."""
    return "08" + random_hex(31)


def key_digest(data):
    """The digest that the KMS takes of a public key object. It is the 32-byte SHAKE-256 of the
    PDAT_KEY domain separator followed by the object's bytes as stored in MinIO (hash_versioned
    in core/threshold-hashing/src/lib.rs, DSEP_PUBDATA_KEY)."""
    return hashlib.shake_256(b"PDAT_KEY" + data).hexdigest(32)
