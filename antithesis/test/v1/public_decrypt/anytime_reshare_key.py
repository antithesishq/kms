#!/usr/bin/env python3
"""Reshares the workload's FHE key into a new epoch of the default context. The decryption
driver also decrypts under the epochs that this command records (pick_epoch in helper_lib.py),
so its plaintext check covers the reshared key shares too.

kms-core-client new-epoch sends the reshare to all four cores and polls each core for the
result. It then checks that every result names the key and preprocessing IDs that were sent,
and that the signature of every result verifies over the published key material. The CLI
succeeds only when all four cores report success, but the protocol tolerates one faulty party.
A failed run can therefore leave an epoch that some cores hold and others do not. Such an epoch
is recorded as unconfirmed, and the decryption driver tries it less often.

This is an anytime command. It runs alongside the decryption drivers, as an operator's reshare
would, and copies of it can run at the same time. Each run uses a fresh epoch ID.
"""

import sys

import helper_lib as h  # first: it sets up the SDK's output before the SDK loads
from antithesis.assertions import always, reachable

h.declare_catalog()

key = h.find_reshare_key()
if key is None:
    print("no key with a recorded preprocessing ID; run first_generate_key.py first, or record")
    print(f"a key generated by hand with: echo <preproc_id> >{h.STATE_DIR}/preproc/<key_id>")
    sys.exit(0)
key_id, preproc_id = key

# The source epoch is the kms-init epoch, or an epoch that an earlier reshare created.
source_epoch = h.DEFAULT_EPOCH_ID
if h.pick("default", "chained") == "chained":
    chained = h.epochs_of(key_id, "confirmed")
    if chained:
        source_epoch = h.pick(*chained)
new_epoch = h.new_epoch_id()

h.enter_scratch_dir()

# The request carries the digests of the key's public material, and every core compares them
# with its own copy before it takes part. Party 1's copy in MinIO is the reference.
digest_field = "xof_key_digest"
keyset = h.fetch(f"{h.S3_PUBLIC}/PUB-p1/CompressedXofKeySet/{key_id}")
if keyset is None:
    digest_field = "server_key_digest"
    keyset = h.fetch(f"{h.S3_PUBLIC}/PUB-p1/ServerKey/{key_id}")
if keyset is None:
    print(f"cannot read the key material of {key_id} from MinIO; no reshare this time")
    sys.exit(0)
public_key = h.fetch(f"{h.S3_PUBLIC}/PUB-p1/PublicKey/{key_id}")
if public_key is None:
    print(f"cannot read the public key of {key_id} from MinIO; no reshare this time")
    sys.exit(0)

previous = (
    f"context_id:{h.DEFAULT_CONTEXT_ID};epoch_id:{source_epoch};"
    f"previous_keys:[key_id={key_id},preproc_id={preproc_id},"
    f"{digest_field}={h.key_digest(keyset)},public_key_digest={h.key_digest(public_key)}]"
)

# --max-iter counts 0.5 s result polls per core.
args = ["-f", "config.toml", "--max-iter", "1200", "new-epoch", "--new-epoch-id", new_epoch,
        "--new-context-id", h.DEFAULT_CONTEXT_ID, "--previous-epoch-params", previous]
rc, output = h.run_cli(args, timeout=900)

inputs = {
    "key_id": key_id,
    "preproc_id": preproc_id,
    "source_epoch": source_epoch,
    "new_epoch": new_epoch,
    "digest_field": digest_field,
    "exit_code": rc,
}

# Errors that the CLI raises only after every core reported the reshare as done: a result names
# another key or preprocessing ID, or its signature does not verify over the published key
# material. Source: do_new_epoch in core-client/src/mpc_epoch.rs.
WRONG_RESULT = [
    "Resharing response did not contain the expected",
    "No resharing response found",
    "Signature verification failed for the reshared key",
]

if rc == 0 and "New epoch created" in output:
    h.record_epoch(new_epoch, key_id, "confirmed")
    always(True, "key reshare result from every KMS party matches the reshared key", inputs)
    if source_epoch != h.DEFAULT_EPOCH_ID:
        reachable("key reshare succeeded from an epoch that a reshare created", inputs)
    sys.exit(0)

err = h.first_line_with(output, WRONG_RESULT)
if err is not None:
    # The cores consider the epoch done, so decryptions under it are worth a try as well.
    h.record_epoch(new_epoch, key_id, "unconfirmed")
    always(
        False,
        "key reshare result from every KMS party matches the reshared key",
        {**inputs, "error": h.clip(err)},
    )
    print(output)
    sys.exit(1)

# The CLI's argument parser exits with 2, so this script built a malformed command.
if rc == 2:
    print("kms-core-client rejected the arguments")
    print(output)
    sys.exit(1)

# Any other failure is a reshare that did not finish everywhere: a core was down, slow or cut
# off, or it rejected the request. The CLI reports a failed reshare as a panic, and the gRPC
# status carries only the code. The epoch is kept, because the other cores can complete it.
h.record_epoch(new_epoch, key_id, "unconfirmed")
lines = output.splitlines()
panic = next((i for i, line in enumerate(lines) if "panicked at" in line), None)
err = "\n".join(lines[panic:panic + 3]) if panic is not None else h.tail(output, 3)
reachable("key reshare attempt ended without a verdict", {**inputs, "error": h.clip(err)})
print(h.tail(output, 20))
sys.exit(0)
